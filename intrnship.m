clc;
clear;
close all;
dt = 0.01;             
T = 30;                
t = 0:dt:T;
N = length(t);
g = 9.81;              
mass = 1.5;            
desired_altitude = 10; 
altitude = zeros(1,N);
velocity = zeros(1,N);
acceleration = zeros(1,N);
altitude(1) = 0;
velocity(1) = 0;
Kp = 3.0;              
Kd = 2.5;             
max_acc = 4;
for k = 1:N-1
    error = desired_altitude - altitude(k);
    command_acc = Kp * error - Kd * velocity(k);
    command_acc = max(min(command_acc, max_acc), -max_acc);
    acceleration(k) = command_acc;
    velocity(k+1) = velocity(k) + acceleration(k)*dt;
    altitude(k+1) = altitude(k) + velocity(k+1)*dt;
    if altitude(k+1) < 0
        altitude(k+1) = 0;
        velocity(k+1) = 0;
    end
end
acceleration(N) = acceleration(N-1);
rng(1);
gyro_roll = 0.5*randn(1,N);
gyro_pitch = 0.5*randn(1,N);
gyro_yaw = 0.5*randn(1,N);
accel_x = 0.05*randn(1,N);
accel_y = 0.05*randn(1,N);
accel_z = g + acceleration + 0.05*randn(1,N);
altitude_error = desired_altitude - altitude;
RMSE = sqrt(mean(altitude_error.^2));
fprintf('BASIC UAV FLIGHT SIMULATION RESULTS\n');
fprintf('----------------------------------\n');
fprintf('Desired altitude: %.2f m\n', desired_altitude);
fprintf('Final simulated altitude: %.2f m\n', altitude(end));
fprintf('Final vertical velocity: %.2f m/s\n', velocity(end));
fprintf('Altitude tracking RMSE: %.3f m\n', RMSE);
figure;
plot(t, altitude, 'b', 'LineWidth', 1.5);
hold on;
yline(desired_altitude, 'r--', 'Desired Altitude');
xlabel('Time (s)');
ylabel('Altitude (m)');
title('UAV Altitude Response');
legend('Actual Altitude', 'Desired Altitude');
grid on;
figure;
plot(t, velocity, 'LineWidth', 1.5);
xlabel('Time (s)');
ylabel('Vertical Velocity (m/s)');
title('UAV Vertical Velocity');
grid on;
figure;
plot(t, acceleration, 'LineWidth', 1.5);
xlabel('Time (s)');
ylabel('Vertical Acceleration (m/s^2)');
title('UAV Vertical Acceleration');
grid on;
figure;
plot(t, gyro_roll, 'LineWidth', 1);
hold on;
plot(t, gyro_pitch, 'LineWidth', 1);
plot(t, gyro_yaw, 'LineWidth', 1);
xlabel('Time (s)');
ylabel('Angular Velocity (degrees/s)');
title('Simulated Gyroscope Measurements');
legend('Roll', 'Pitch', 'Yaw');
grid on;
figure;
plot(t, accel_x, 'LineWidth', 1);
hold on;
plot(t, accel_y, 'LineWidth', 1);
plot(t, accel_z, 'LineWidth', 1);
xlabel('Time (s)');
ylabel('Specific Force (m/s^2)');
title('Simulated Accelerometer Measurements');
legend('X-axis', 'Y-axis', 'Z-axis');
grid on;
figure;
plot(t, altitude_error, 'LineWidth', 1.5);
xlabel('Time (s)');
ylabel('Altitude Error (m)');
title('UAV Altitude Tracking Error');
grid on;
fprintf('\nSimulation completed successfully.\n');